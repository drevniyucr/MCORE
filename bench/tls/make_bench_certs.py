#!/usr/bin/env python3
"""
make_bench_certs.py — test PKI for the MQTT/TLS bench (same shape as the
goz-shuttle one): a CA, the broker certificate and one client certificate,
all P-256 / ECDSA-SHA256, the only kind the firmware's mbedTLS accepts.

    python bench/tls/make_bench_certs.py [--broker 192.168.99.10] [--client mcore-01]

Writes, all git-ignored because they hold private keys:
    bench/tls/out/                 ca.*, broker.*, <client>.* (PEM) for Mosquitto/mosquitto_sub
    app/tls_bench_creds.hpp        CA + client certificate + client key as DER arrays;
                                   the firmware enables the TLS demo when it exists
An existing CA is reused, so re-running only re-issues the leaf certificates.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "bench" / "tls" / "out"
HEADER = ROOT / "app" / "tls_bench_creds.hpp"
DAYS = 3650


def find_openssl() -> str:
    found = shutil.which("openssl")
    if found:
        return found
    # Git for Windows ships one; it is not on PATH outside Git Bash
    for base in (os.environ.get("ProgramFiles", r"C:\Program Files"), r"C:\Program Files (x86)"):
        cand = Path(base) / "Git" / "usr" / "bin" / "openssl.exe"
        if cand.exists():
            return str(cand)
    sys.exit("openssl not found")


OPENSSL = find_openssl()


def ssl(*args: str, stdin: bytes | None = None) -> bytes:
    env = dict(os.environ, MSYS_NO_PATHCONV="1")  # keep "/CN=..." intact under MSYS
    return subprocess.run([OPENSSL, *args], input=stdin, env=env, check=True,
                          capture_output=True, cwd=OUT).stdout


def key(name: str) -> None:
    ssl("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", f"{name}.key")


def issue(name: str, subject: str, ext: str) -> None:
    key(name)
    ssl("req", "-new", "-key", f"{name}.key", "-subj", subject, "-out", f"{name}.csr")
    (OUT / f"{name}.ext").write_text(ext)
    ssl("x509", "-req", "-in", f"{name}.csr", "-CA", "ca.crt", "-CAkey", "ca.key", "-CAcreateserial",
        "-sha256", "-days", str(DAYS), "-extfile", f"{name}.ext", "-out", f"{name}.crt")
    (OUT / f"{name}.csr").unlink()
    (OUT / f"{name}.ext").unlink()


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"inline constexpr uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--broker", default="192.168.99.10", help="broker IP (goes into its certificate SAN)")
    ap.add_argument("--client", default="mcore-01", help="client id = certificate CN")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    if not (OUT / "ca.key").exists():
        key("ca")
        ssl("req", "-new", "-x509", "-key", "ca.key", "-sha256", "-days", str(DAYS),
            "-subj", "/O=MCORE bench/CN=MCORE bench CA",
            "-addext", "basicConstraints=critical,CA:TRUE",
            "-addext", "keyUsage=critical,keyCertSign,cRLSign", "-out", "ca.crt")

    issue("broker", "/O=MCORE bench/CN=broker",
          "basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature\n"
          f"extendedKeyUsage=serverAuth\nsubjectAltName=IP:{a.broker},DNS:broker\n")
    issue(a.client, f"/O=MCORE bench/CN={a.client}",
          "basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n")

    ca_der = ssl("x509", "-in", "ca.crt", "-outform", "DER")
    crt_der = ssl("x509", "-in", f"{a.client}.crt", "-outform", "DER")
    key_der = ssl("ec", "-in", f"{a.client}.key", "-outform", "DER")

    HEADER.write_text(
        "// GENERATED by bench/tls/make_bench_certs.py — git-ignored, holds a private key.\n"
        "// Bench credentials for app/mqtt_demo.cpp (MQTT over TLS to Mosquitto).\n"
        "#pragma once\n#include <cstdint>\n\n"
        f'inline constexpr char BENCH_BROKER_HOST[] = "{a.broker}";\n'
        f'inline constexpr char BENCH_CLIENT_ID[] = "{a.client}";\n\n'
        + c_array("BENCH_CA_DER", ca_der) + "\n"
        + c_array("BENCH_CLIENT_CERT_DER", crt_der) + "\n"
        + c_array("BENCH_CLIENT_KEY_DER", key_der),
        encoding="utf-8", newline="\n")
    print(f"certificates in {OUT}")
    print(f"firmware credentials in {HEADER}")


if __name__ == "__main__":
    main()

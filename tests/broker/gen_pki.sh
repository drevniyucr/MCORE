#!/usr/bin/env bash
# Generates a TEST-ONLY PKI for the local MQTT broker used by MCORE tests:
#   pki/ca.crt, ca.key           test CA (EC P-256)
#   pki/server.crt, server.key   broker certificate (EC P-256)
#   pki/server_rsa.crt/.key      broker certificate (RSA 2048, host tests)
#   pki/client.crt, client.key   device certificate for mutual TLS (EC P-256)
# and copies the CA certificate to app_cm4/certs/broker_ca.pem, which the
# Cortex-M4 firmware embeds.
#
# Private keys stay in pki/ (git-ignored). Re-running replaces everything,
# so rebuild the firmware afterwards.
#
# Usage: tests/broker/gen_pki.sh [extra broker IP ...]
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash: keep "/CN=..." as is

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
pki="$here/pki"
mkdir -p "$pki"
cd "$pki"

# Names the broker certificate is valid for. 192.168.0.10 is the PC adapter
# wired to the board (app_cm4/net_config.hpp: BROKER_IP / BROKER_NAME).
san="DNS:localhost,DNS:mcore-broker,IP:127.0.0.1,IP:192.168.0.10"
for ip in "$@"; do san="$san,IP:$ip"; done

days=825

openssl ecparam -name prime256v1 -genkey -noout -out ca.key
openssl req -x509 -new -key ca.key -sha256 -days 3650 -out ca.crt \
  -subj "/O=MCORE/CN=MCORE TEST CA" \
  -addext "basicConstraints=critical,CA:TRUE" \
  -addext "keyUsage=critical,keyCertSign,cRLSign"

issue() {   # name keytype subject extensions
  local name=$1 keytype=$2 subj=$3 ext=$4
  if [ "$keytype" = rsa ]; then
    openssl genrsa -out "$name.key" 2048 2>/dev/null
  else
    openssl ecparam -name prime256v1 -genkey -noout -out "$name.key"
  fi
  openssl req -new -key "$name.key" -subj "$subj" -out "$name.csr"
  printf '%s\n' "$ext" > "$name.ext"
  openssl x509 -req -in "$name.csr" -CA ca.crt -CAkey ca.key -CAcreateserial \
    -days "$days" -sha256 -extfile "$name.ext" -out "$name.crt" 2>/dev/null
  rm -f "$name.csr" "$name.ext"
}

server_ext="basicConstraints=CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
subjectAltName=$san"
issue server     ec  "/O=MCORE/CN=mcore-broker" "$server_ext"
issue server_rsa rsa "/O=MCORE/CN=mcore-broker" "$server_ext"
issue client     ec  "/O=MCORE/CN=mcore-agv-001" "basicConstraints=CA:FALSE
keyUsage=critical,digitalSignature
extendedKeyUsage=clientAuth"

mkdir -p "$root/app_cm4/certs"
{
  echo "# MCORE TEST CA - generated by tests/broker/gen_pki.sh."
  echo "# Replace with the CA of your production broker."
  cat ca.crt
} > "$root/app_cm4/certs/broker_ca.pem"

echo "PKI in $pki (SAN: $san)"
echo "CA copied to app_cm4/certs/broker_ca.pem - rebuild the firmware."
